"""The sole entry point for the numerical submission.

Run from the project root with: python code/run_all.py
"""

from __future__ import annotations

import csv
from pathlib import Path
import re

from experiments import run_all as run_experiments
from depth_benchmarks import main as run_depth_comparisons
from variable_diffusion import run as run_variable_diffusion


ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "data"
FIGURES = ROOT / "figures"
GENERATED = ROOT / "generated"


def latex_escape(value: str) -> str:
    replacements = {
        "\\": r"\textbackslash{}",
        "&": r"\&",
        "%": r"\%",
        "$": r"\$",
        "#": r"\#",
        "_": r"\_",
        "{": r"\{",
        "}": r"\}",
        "~": r"\textasciitilde{}",
        "^": r"\textasciicircum{}",
    }
    return "".join(replacements.get(char, char) for char in value)


def convert_csv_to_latex(csv_path: Path, output_path: Path) -> None:
    """Preserve every CSV field in an appendix-ready LaTeX table."""
    with csv_path.open(newline="", encoding="utf-8") as source:
        reader = csv.reader(source)
        rows = list(reader)
    if not rows:
        raise ValueError(f"Empty CSV: {csv_path}")
    width = len(rows[0])
    if any(len(row) != width for row in rows):
        raise ValueError(f"Unequal column counts: {csv_path}")
    title = latex_escape(csv_path.stem.replace("_", " "))
    label = re.sub(r"[^a-z0-9-]", "-", output_path.stem.lower().replace("_", "-"))
    lines = [
        "% Auto-generated by code/run_all.py from data/" + csv_path.relative_to(DATA).as_posix(),
        "% Requires graphicx and booktabs in the main document.",
        r"\begin{table}[htbp]",
        r"\centering",
        r"\resizebox{\linewidth}{!}{%",
        r"\begin{tabular}{" + "l" * width + "}",
        r"\toprule",
        " & ".join(latex_escape(value) for value in rows[0]) + r" \\",
        r"\midrule",
    ]
    lines.extend(" & ".join(latex_escape(value) for value in row) + r" \\" for row in rows[1:])
    lines.extend([
        r"\bottomrule",
        r"\end{tabular}%",
        r"}",
        rf"\caption{{Raw numerical data: {title}.}}",
        rf"\label{{tab:raw-{label}}}",
        r"\end{table}",
        "",
    ])
    output_path.write_text("\n".join(lines), encoding="utf-8")


def main() -> None:
    for directory in (DATA, FIGURES, GENERATED):
        directory.mkdir(parents=True, exist_ok=True)

    # Numerical routines write their intermediate files together. Once all
    # computations pass, classify the generated outputs by their file type.
    run_experiments(GENERATED)
    for path in list(GENERATED.iterdir()):
        if path.suffix == ".csv" or path.suffix == ".json":
            path.replace(DATA / path.name)
        elif path.suffix == ".png":
            path.replace(FIGURES / path.name)

    # Separate all-Dirichlet square and L-shaped comparisons. Their metadata
    # lives in data/depth_extension and cannot overwrite the FO/G run record.
    run_depth_comparisons(ROOT)
    run_variable_diffusion(ROOT)

    raw_tables = GENERATED / "raw_tables"
    raw_tables.mkdir(exist_ok=True)
    for csv_path in sorted(DATA.rglob("*.csv")):
        table_name = "_".join(csv_path.relative_to(DATA).with_suffix("").parts) + ".tex"
        convert_csv_to_latex(csv_path, raw_tables / table_name)

    print("All checks passed.")
    print(f"CSV and metadata: {DATA}")
    print(f"Figures: {FIGURES}")
    print(f"LaTeX tables: {GENERATED}")


if __name__ == "__main__":
    main()
